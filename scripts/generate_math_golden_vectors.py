#!/usr/bin/env python3
"""
scripts/generate_math_golden_vectors.py
======================================
Generates deterministic golden test vectors for Python <-> C++ mathematical equivalence.
"""

import json
import sys
import os
sys.path.insert(0, os.path.abspath('.'))
import numpy as np
from idr_pipeline.eskf_fusion import (
    euler_to_rotation_matrix,
    rotation_matrix_to_euler,
    rodrigues,
    skew_symmetric,
    renormalize_rotation_matrix,
    wrap_pi
)

def generate_golden_vectors():
    np.random.seed(42)
    vectors = []

    for i in range(100):
        roll = float(np.random.uniform(-0.5, 0.5))
        pitch = float(np.random.uniform(-0.5, 0.5))
        yaw = float(np.random.uniform(0.0, 2.0 * np.pi))

        R = euler_to_rotation_matrix(roll, pitch, yaw)
        r_rec, p_rec, y_rec = rotation_matrix_to_euler(R)

        rot_vec = np.random.randn(3) * 1.5
        R_rod = rodrigues(rot_vec)

        v_rand = np.random.randn(3)
        K_skew = skew_symmetric(v_rand)

        vectors.append({
            "idx": i,
            "roll": roll,
            "pitch": pitch,
            "yaw": yaw,
            "R": R.tolist(),
            "euler_rec": [r_rec, p_rec, y_rec],
            "rot_vec": rot_vec.tolist(),
            "R_rod": R_rod.tolist(),
            "v_rand": v_rand.tolist(),
            "K_skew": K_skew.tolist()
        })

    with open("tests/cross_language/math_golden_vectors.json", "w") as f:
        json.dump(vectors, f, indent=2)

    with open("idr-core/tests/math_golden_vectors.hpp", "w") as f:
        f.write("// Auto-generated by scripts/generate_math_golden_vectors.py\n#pragma once\n\n")
        f.write("struct MathGoldenVector {\n")
        f.write("    double roll, pitch, yaw;\n")
        f.write("    double R[9];\n")
        f.write("    double euler_rec[3];\n")
        f.write("    double rot_vec[3];\n")
        f.write("    double R_rod[9];\n")
        f.write("    double v_rand[3];\n")
        f.write("    double K_skew[9];\n")
        f.write("};\n\n")
        f.write("inline const MathGoldenVector kMathGoldenVectors[100] = {\n")
        for v in vectors:
            r_flat = [x for row in v["R"] for x in row]
            r_rod_flat = [x for row in v["R_rod"] for x in row]
            k_skew_flat = [x for row in v["K_skew"] for x in row]
            f.write("    {" + f"{v['roll']}, {v['pitch']}, {v['yaw']},\n")
            f.write("     {" + ", ".join(f"{x:.17g}" for x in r_flat) + "},\n")
            f.write("     {" + ", ".join(f"{x:.17g}" for x in v['euler_rec']) + "},\n")
            f.write("     {" + ", ".join(f"{x:.17g}" for x in v['rot_vec']) + "},\n")
            f.write("     {" + ", ".join(f"{x:.17g}" for x in r_rod_flat) + "},\n")
            f.write("     {" + ", ".join(f"{x:.17g}" for x in v['v_rand']) + "},\n")
            f.write("     {" + ", ".join(f"{x:.17g}" for x in k_skew_flat) + "}},\n")
        f.write("};\n")

    print(f"Generated 100 golden vectors -> idr-core/tests/math_golden_vectors.hpp")


if __name__ == "__main__":
    generate_golden_vectors()
